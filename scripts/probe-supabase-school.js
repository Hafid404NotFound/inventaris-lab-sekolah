const fs = require('fs');
const path = require('path');

const envPath = ['.env.local', 'env.local'].map(p => path.resolve(process.cwd(), p)).find(p => fs.existsSync(p));
const env = {};
if (envPath) {
  for (const line of fs.readFileSync(envPath, 'utf8').split(/\r?\n/)) {
    if (!line.trim() || line.trim().startsWith('#')) continue;
    const i = line.indexOf('=');
    if (i > -1) env[line.slice(0, i).trim()] = line.slice(i + 1).trim();
  }
}

console.log('envPath', envPath);
console.log('url', env.NEXT_PUBLIC_SUPABASE_URL);
console.log('hasKey', !!env.NEXT_PUBLIC_SUPABASE_ANON_KEY);

const { createClient } = require('@supabase/supabase-js');
const supabase = createClient(env.NEXT_PUBLIC_SUPABASE_URL, env.NEXT_PUBLIC_SUPABASE_ANON_KEY, {
  auth: { persistSession: false, autoRefreshToken: false },
});

(async () => {
  const d = '11111111-1111-4111-8111-111111111111';
  const q1 = await supabase.from('schools').select('*').eq('id', d).maybeSingle();
  console.log('q1', JSON.stringify(q1, null, 2));
  const q2 = await supabase.from('schools').upsert([
    { id: d, name: 'Default School', address: 'Auto-generated by app', logo_url: null },
  ], { onConflict: 'id' }).select();
  console.log('q2', JSON.stringify(q2, null, 2));
  const q3 = await supabase.from('schools').select('*').eq('id', d).maybeSingle();
  console.log('q3', JSON.stringify(q3, null, 2));
})();
