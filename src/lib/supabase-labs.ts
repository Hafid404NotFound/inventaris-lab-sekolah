import { supabase } from "./supabase";
import { Lab } from "@/types/database";
import { createCategory } from "./supabase-categories";

export const DEFAULT_SCHOOL_ID = "11111111-1111-4111-8111-111111111111";

export function isValidUuid(value?: string | null) {
  if (!value) return false;
  return /^[0-9a-f]{8}-[0-9a-f]{4}-[1-5][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/i.test(value);
}

type LabQueryResultList = {
  data: Lab[] | null;
  error: unknown;
};

type LabQueryResultSingle = {
  data: Lab | null;
  error: unknown;
};

type LabQueryChain = {
  select: (columns?: string) => LabQueryChain;
  eq: (column: string, value: string) => LabQueryChain;
  order: (
    column: string,
    options?: { ascending?: boolean },
  ) => Promise<LabQueryResultList>;
  single: () => Promise<LabQueryResultSingle>;
  update: (payload: Record<string, unknown>) => LabQueryChain;
  delete: () => {
    eq: (column: string, value: string) => Promise<{ error: unknown }>;
  };
};

type LabCrudClient = {
  from: (table: "labs") => {
    select: (columns?: string) => LabQueryChain;
    insert: (rows: Array<Record<string, unknown>>) => LabQueryChain;
    update: (payload: Record<string, unknown>) => LabQueryChain;
    delete: () => {
      eq: (column: string, value: string) => Promise<{ error: unknown }>;
    };
  };
};

export async function getOrCreateDefaultSchool() {
  try {
    const client = supabase as unknown as {
      from: (table: "schools") => {
        select: (columns: string) => {
          eq: (column: string, value: string) => {
            maybeSingle: () => Promise<{
              data: { id: string } | null;
              error: { code?: string } | null;
            }>;
          };
        };
        upsert: (
          rows: Array<Record<string, unknown>>,
          options?: { onConflict?: string },
        ) => {
          select: (columns: string) => {
            single: () => Promise<{
              data: { id: string } | null;
              error: { code?: string } | null;
            }>;
          };
        };
      };
    };

    const { data: existingSchool, error: selectError } = await client
      .from("schools")
      .select("id")
      .eq("id", DEFAULT_SCHOOL_ID)
      .maybeSingle();

    if (selectError && selectError.code !== "PGRST116") {
      console.error("Error checking default school:", selectError);
    }

    if (existingSchool?.id) {
      return existingSchool.id;
    }

    const { data: createdSchool, error: upsertError } = await client
      .from("schools")
      .upsert(
        [
          {
            id: DEFAULT_SCHOOL_ID,
            name: "Default School",
            address: "Auto-generated by app",
            logo_url: null,
          },
        ],
        { onConflict: "id" },
      )
      .select("id")
      .single();

    if (upsertError) {
      console.error("Error creating default school:", upsertError);
      return DEFAULT_SCHOOL_ID;
    }

    return createdSchool?.id || DEFAULT_SCHOOL_ID;
  } catch (error) {
    console.error("Exception in getOrCreateDefaultSchool:", error);
    return DEFAULT_SCHOOL_ID;
  }
}

/**
 * Get all labs
 */
export async function getLabs() {
  const client = supabase as unknown as LabCrudClient;

  try {
    const { data, error } = await client
      .from("labs")
      .select("*")
      .order("name", { ascending: true });

    if (error) {
      console.error("Error fetching labs:", error);
      return [];
    }

    return data || [];
  } catch (error) {
    console.error("Exception in getLabs:", error);
    return [];
  }
}

