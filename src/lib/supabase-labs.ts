/**
 * Create new lab
 */
export async function createLab(
  lab: Pick<Lab, "school_id" | "name"> &
    Partial<Pick<Lab, "code" | "pic_name" | "description">>,
) {
  const client = supabase as unknown as LabCrudClient;

  try {
    const ensuredSchoolId = await getOrCreateDefaultSchool();
    const schoolId = isValidUuid(lab.school_id) && lab.school_id !== DEFAULT_SCHOOL_ID
      ? lab.school_id
      : ensuredSchoolId;

    const payload = {
      school_id: schoolId,
      code: lab.code ?? null,
      name: lab.name,
      pic_name: lab.pic_name ?? null,
      description: lab.description ?? null,
    };

    console.log("Creating lab with payload:", payload);

    const { data, error } = await client
      .from("labs")
      .insert([payload])
      .select()
      .single();

    if (error) {
      console.error("Error creating lab in Supabase:", {
        code: error instanceof Object && "code" in error ? error.code : "UNKNOWN",
        message: error instanceof Object && "message" in error ? error.message : String(error),
        details: error instanceof Object && "details" in error ? error.details : undefined,
        hint: error instanceof Object && "hint" in error ? error.hint : undefined,
      });
      throw new Error(`Failed to create lab: ${error instanceof Object && "message" in error ? error.message : String(error)}`);
    }

    if (!data) {
      throw new Error("No data returned from insert operation");
    }

    const createdLab = data as Lab;

    try {
      await Promise.all([
        createCategory({
          lab_id: createdLab.id,
          name: "Peralatan Umum",
          type: "asset",
        }),
        createCategory({
          lab_id: createdLab.id,
          name: "Bahan Praktikum",
          type: "consumable",
        }),
      ]);
    } catch (categoryError) {
      console.error("Warning: failed to create default categories for lab:", categoryError);
    }

    return createdLab;
  } catch (error) {
    console.error("Exception in createLab:", error);
    throw error;
  }
}

/**
 * Update existing lab
 */
export async function updateLab(id: string, lab: Partial<Lab>) {
  const client = supabase as unknown as LabCrudClient;

  try {
    const payload = { ...lab };
    delete payload.id;
    delete payload.created_at;
    delete payload.school_id; // Don't allow updating school_id
    delete payload.category; // Remove category field as it's not used in new schema
    delete payload.location; // Remove location field as it's not used in new schema

    console.log("Updating lab with payload:", payload);
    console.log("Lab ID:", id);

    const { data, error } = await client
      .from("labs")
      .update(payload)
      .eq("id", id)
      .select()
      .single();

    if (error) {
      console.error("Error updating lab:", {
        code: error instanceof Object && "code" in error ? error.code : "UNKNOWN",
        message: error instanceof Object && "message" in error ? error.message : String(error),
        details: error instanceof Object && "details" in error ? error.details : undefined,
        hint: error instanceof Object && "hint" in error ? error.hint : undefined,
      });
      throw new Error(`Failed to update lab: ${error instanceof Object && "message" in error ? error.message : String(error)}`);
    }

    if (!data) {
      throw new Error("No data returned from update operation");
    }

    return data as Lab;
  } catch (error) {
    console.error("Exception in updateLab:", error);
    throw error;
  }
}

